    // Release signing is driven entirely by environment variables so the same
    // build.gradle.kts works locally and in CI without ever hardcoding secrets.
    // If KEYSTORE_PATH isn't set (e.g. a plain debug build, or a fork PR with no
    // access to secrets), no signingConfig is attached and assembleRelease still
    // succeeds but produces an unsigned APK — it just won't be installable as-is.
    val keystorePathEnv = System.getenv("KEYSTORE_PATH")
    val hasReleaseSigning = !keystorePathEnv.isNullOrBlank()

    signingConfigs {
        if (hasReleaseSigning) {
            create("release") {
                storeFile = file(keystorePathEnv!!)
                storePassword = System.getenv("KEYSTORE_PASSWORD")
                keyAlias = System.getenv("KEY_ALIAS")
                keyPassword = System.getenv("KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            if (hasReleaseSigning) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
        debug {
            isMinifyEnabled = false
            applicationIdSuffix = ".debug"
        }
    }

    compileOptions {
